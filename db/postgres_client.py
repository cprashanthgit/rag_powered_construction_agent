# -*- coding: utf-8 -*-
"""
db/postgres_client.py — Async PostgreSQL connection pool and query functions

This module owns the single asyncpg connection pool for the entire app.
All database operations are async so they never block the FastAPI event loop.

Tables used (defined in db/schema.sql, auto-created by Docker on first boot):
    users      — registered users with hashed passwords and roles
    query_log  — every RAG query that goes through the API
    feedback   — thumbs up/down ratings on specific answers

Connection string is built from .env variables:
    POSTGRES_HOST, POSTGRES_PORT, POSTGRES_DB, POSTGRES_USER, POSTGRES_PASSWORD
"""

import json
import os
from typing import Optional

import asyncpg

# ── Connection string ──────────────────────────────────────────────────────────
DATABASE_URL = (
    f"postgresql://{os.getenv('POSTGRES_USER', 'cnst_user')}"
    f":{os.getenv('POSTGRES_PASSWORD', 'devpassword123')}"
    f"@{os.getenv('POSTGRES_HOST', 'localhost')}"
    f":{os.getenv('POSTGRES_PORT', '5432')}"
    f"/{os.getenv('POSTGRES_DB', 'cnst_rag')}"
)

# ── Connection pool singleton ──────────────────────────────────────────────────
_pool: Optional[asyncpg.Pool] = None


async def get_pool() -> asyncpg.Pool:
    """
    Return the shared connection pool, creating it on first call.

    Pool settings:
        min_size=2  — always keep 2 connections open (fast response)
        max_size=10 — max 10 simultaneous queries (enough for demo scale)
        command_timeout=30 — fail loudly instead of hanging forever
    """
    global _pool
    if _pool is None:
        _pool = await asyncpg.create_pool(
            DATABASE_URL,
            min_size=2,
            max_size=10,
            command_timeout=30,
        )
    return _pool


# ══════════════════════════════════════════════════════════════════════════════
# User queries
# ══════════════════════════════════════════════════════════════════════════════

async def get_user_by_email(email: str) -> Optional[asyncpg.Record]:
    """
    Fetch a user row by email address.
    Returns None if the user doesn't exist or is inactive.
    """
    pool = await get_pool()
    return await pool.fetchrow(
        "SELECT id, email, role, password_hash FROM users WHERE email=$1 AND is_active=true",
        email,
    )


async def update_last_login(user_id: str) -> None:
    """Update the last_login timestamp when a user successfully logs in."""
    pool = await get_pool()
    await pool.execute(
        "UPDATE users SET last_login = NOW() WHERE id=$1",
        user_id,
    )


# ══════════════════════════════════════════════════════════════════════════════
# Query logging
# ══════════════════════════════════════════════════════════════════════════════

async def log_query(
    query_id:     str,
    session_id:   str,
    user_id:      Optional[str],
    user_role:    str,
    query:        str,
    answer:       str,
    sources:      list,
    confidence:   float,
    retrieval_ms: int,
    generation_ms: int,
    total_ms:     int,
    cache_hit:    bool,
    llm_backend:  str,
    llm_model:    str,
) -> None:
    """
    Insert a completed RAG query into the query_log table.

    query_id is pre-generated by the API endpoint so it can be returned
    in the response immediately (before this background task runs).
    Called as a FastAPI BackgroundTask so it never blocks the response.
    """
    pool = await get_pool()
    await pool.execute(
        """
        INSERT INTO query_log (
            id, session_id, user_id, user_role, query, answer, sources,
            confidence, retrieval_ms, generation_ms, total_ms,
            cache_hit, llm_backend, llm_model
        )
        VALUES ($1::uuid, $2, $3, $4, $5, $6, $7::jsonb, $8, $9, $10, $11, $12, $13, $14)
        ON CONFLICT (id) DO NOTHING
        """,
        query_id,
        session_id,
        user_id if user_id != "anonymous" else None,
        user_role,
        query,
        answer,
        json.dumps(sources),
        confidence,
        retrieval_ms,
        generation_ms,
        total_ms,
        cache_hit,
        llm_backend,
        llm_model,
    )



