# Feedback
# ══════════════════════════════════════════════════════════════════════════════

async def record_feedback(query_id: str, rating: int, comment: str = "") -> None:
    """
    Record a thumbs up (+1) or thumbs down (-1) rating for a specific answer.

    Args:
        query_id: UUID of the query_log row being rated
        rating:   +1 (helpful) or -1 (not helpful)
        comment:  Optional text comment from the user
    """
    pool = await get_pool()
    await pool.execute(
        "INSERT INTO feedback (query_id, rating, comment) VALUES ($1, $2, $3)",
        query_id,
        rating,
        comment,
    )


async def get_feedback_stats() -> dict:
    """
    Return aggregate satisfaction statistics across all feedback.

    Returns:
        {
            "total":            int   — total ratings submitted
            "positive":         int   — thumbs up count
            "satisfaction_pct": float — percentage of positive ratings
        }
    """
    pool = await get_pool()
    row = await pool.fetchrow(
        """
        SELECT
            COUNT(*)                                                    AS total,
            SUM(CASE WHEN rating = 1 THEN 1 ELSE 0 END)               AS positive,
            ROUND(AVG(CASE WHEN rating = 1 THEN 100.0 ELSE 0 END), 1) AS satisfaction_pct
        FROM feedback
        """
    )
    return {
        "total":            int(row["total"]),
        "positive":         int(row["positive"] or 0),
        "satisfaction_pct": float(row["satisfaction_pct"] or 0.0),
    }


async def get_recent_queries(limit: int = 20) -> list:
    """
    Return the most recent queries from query_log (for admin dashboard use).
    """
    pool = await get_pool()
    rows = await pool.fetch(
        """
        SELECT query, answer, total_ms, cache_hit, user_role, created_at
        FROM query_log
        ORDER BY created_at DESC
        LIMIT $1
        """,
        limit,
    )
    return [dict(row) for row in rows]
